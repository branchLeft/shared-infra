    def test_wrong_ecosystem_is_refused(self) -> None:
        """The right directory under another ecosystem does not read requirements.txt."""
        self.put(DEPENDABOT.replace("'uv'", "'npm'"))
        self.assert_found("dependabot.yml has no scheduled uv update for /ansible")

    def test_entry_without_a_schedule_is_refused(self) -> None:
        """Dependabot refuses an entry with no schedule, so it would watch nothing."""
        self.put(DEPENDABOT.replace("    schedule:\n      interval: 'weekly'\n", "", 2))
        self.assert_found("dependabot.yml has no scheduled uv update for /ansible")

    def test_missing_file_is_refused(self) -> None:
        """No configuration means no update route."""
        (self.root / ".github" / "dependabot.yml").unlink()
