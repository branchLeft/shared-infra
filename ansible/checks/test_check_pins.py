class ProvenanceTests(PinCase):
    """requirements.in, the header and the `# via` comments explain every line of the lock."""

    def test_missing_input_file_is_refused(self) -> None:
        """Without requirements.in Dependabot cannot recompile the lock."""
        (self.ansible / "requirements.in").unlink()
        self.assert_found("requirements.in cannot be read")

    def test_loose_input_line_is_refused(self) -> None:
        """A range in the input would let a recompile move a tool unasked."""
        for loose in (
            "ruff>=0.17.0",
            "ruff",
            "ruff==0.17.*",
            "ruff==0.17.0 --hash=sha256:" + "a" * 64,
        ):
            with self.subTest(line=loose):
                self.put_input(input_text().replace("ruff==0.17.0", loose))
                self.assert_found("requirements.in line")

    def test_input_missing_a_tool_is_refused(self) -> None:
        """A tool the input does not name is one nobody chose."""
        self.put_input(input_text().replace("mypy==2.4.0\n", ""))
        self.assert_found("requirements.in does not name mypy")

    def test_input_pin_differing_from_the_lock_is_refused(self) -> None:
        """An input edited without recompiling leaves the lock on the old version."""
        self.put_input(input_text().replace("ruff==0.17.0", "ruff==0.18.0"))
        self.assert_found("requirements.in pins ruff 0.18.0, requirements.txt has 0.17.0")

    def test_chosen_package_missing_from_the_input_is_refused(self) -> None:
        """A lock entry marked as chosen that the input does not name is unexplained."""
        self.put_lock(lock_text() + lock_entry("extra-tool", "1.0.0"))
        self.assert_found("marks extra-tool as chosen but requirements.in does not name it")

    def test_input_package_not_marked_in_the_lock_is_refused(self) -> None:
        """An input line the lock does not mark chosen means the lock was not compiled from it."""
        self.put_input(input_text() + "extra-tool==1.0.0\n")
        self.assert_found("requirements.in names extra-tool but requirements.txt does not mark it")

    def test_entry_with_no_reason_is_refused(self) -> None:
        """A lock line that nothing explains is one a person added by hand."""
        self.put_lock(lock_text() + lock_entry("stowaway", "1.0.0", via=""))
        self.assert_found("pins stowaway with no '# via' comment")

    def test_pulled_package_with_a_reason_passes(self) -> None:
        """The control case: a package pulled in by another carries a reason and needs no input."""
        self.put_lock(lock_text() + lock_entry("helper", "1.0.0", via=VIA_PULLED))
        self.assertEqual(self.findings(), [])

    def test_header_must_record_how_the_lock_was_made(self) -> None:
        """Each fact Dependabot or a maintainer reads from the header is required."""
        for fact, text in (
            ("--universal", " --universal"),
            ("--generate-hashes", " --generate-hashes"),
            ("--python-version", " --python-version 3.12"),
            ("uv pip compile", "uv pip compile"),
        ):
            with self.subTest(fact=fact):
                self.put_lock(lock_text().replace(text, "", 1))
                self.assert_found(f"requirements.txt header does not record {fact}")

    def test_lock_without_a_header_is_refused(self) -> None:
        """A lock compiled with --no-header has lost the record of how it was made."""
        self.put_lock(lock_text(header=""))
        self.assert_found("requirements.txt header does not record --universal")


class DependabotTests(PinCase):
    """Dependabot watches the lock, so an upstream release raises a pull request on its own."""

    def put(self, text: str) -> None:
        """Replace dependabot.yml."""
        (self.root / ".github" / "dependabot.yml").write_text(text, encoding="utf-8")

    def test_missing_entry_is_refused(self) -> None:
        """A file with other ecosystems only leaves the Ansible lock unwatched."""
