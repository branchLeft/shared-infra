"""Tests for the pin check: a valid tree passes and each way of breaking the lock is found."""

from __future__ import annotations

import contextlib
import io
import re
import shutil
import tempfile
import unittest
from pathlib import Path

import check_pins

HASH = "--hash=sha256:" + "a" * 64
OTHER_HASH = "--hash=sha256:" + "b" * 64
TOOLS = {
    "ansible": "14.5.0",
    "ansible-core": "2.21.5",
    "ansible-lint": "26.10.1",
    "molecule": "26.10.0",
    "molecule-plugins[docker]": "26.10.12",
    "yamllint": "1.38.0",
    "mypy": "2.4.0",
    "ruff": "0.17.0",
    "ruamel-yaml": "0.19.1",
}
DEPENDABOT = (
    "version: 2\nupdates:\n  - package-ecosystem: 'npm'\n    directory: '/'\n"
    "    schedule:\n      interval: 'weekly'\n"
    "  - package-ecosystem: 'uv'\n    directory: '/ansible'\n"
    "    schedule:\n      interval: 'weekly'\n"
    "  - package-ecosystem: 'pip'\n    directory: '/ansible/checks'\n"
    "    schedule:\n      interval: 'weekly'\n"
)
PIP_PIN = f"# the pip the parity test asks\npip==26.1.2 \\\n    {HASH}\n"
EMPTY_COLLECTIONS = "collections: []\n"
LINT_HOOK = (
    "repos:\n  - repo: https://github.com/ansible/ansible-lint\n    rev: {rev}\n"
    "    hooks:\n      - id: ansible-lint\n"
)
LOCAL_ONLY = "repos:\n  - repo: local\n    hooks:\n      - id: ansible-lint\n"


HEADER = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv pip compile requirements.in --universal --python-version 3.12 "
    "--generate-hashes --output-file requirements.txt\n"
)
VIA_CHOSEN = "    # via -r requirements.in\n"
VIA_PULLED = "    # via\n    #   ansible\n"
VIA_CHOSEN_AND_PULLED = "    # via\n    #   -r requirements.in\n    #   ansible-lint\n"


def lock_entry(name: str, version: str, marker: str = "", via: str = VIA_CHOSEN) -> str:
    """Return one lock entry the way `uv pip compile` writes it: a pin, its hashes, its reason."""
    hashes = f"    {HASH} \\\n    {OTHER_HASH}\n"
    return f"{name}=={version}{marker} \\\n{hashes}{via}"


def lock_text(header: str = HEADER) -> str:
    """Return a valid lock holding every named tool; all but ansible-core are chosen."""
    return header + "".join(
        lock_entry(name, version, via=VIA_PULLED if name == "ansible-core" else VIA_CHOSEN)
        for name, version in TOOLS.items()
    )


def input_text() -> str:
    """Return the requirements.in that matches lock_text: the chosen tools, exact, no hashes."""
    return "".join(
        f"{name}=={version}\n" for name, version in TOOLS.items() if name != "ansible-core"
    )


class PinCase(unittest.TestCase):
    """A test case that builds a repository holding a valid lock and update route."""

    def setUp(self) -> None:
        """Create the tree and remember where its parts are."""
        self.root = Path(tempfile.mkdtemp(prefix="pins-test-"))
        self.addCleanup(shutil.rmtree, self.root, True)
        self.ansible = self.root / "ansible"
        self.ansible.mkdir()
        (self.root / ".github").mkdir()
        self.put_lock(lock_text())
        self.put_input(input_text())
        (self.ansible / "requirements.yml").write_text(EMPTY_COLLECTIONS, encoding="utf-8")
        (self.ansible / "checks").mkdir()
        self.put_pip_pin(PIP_PIN)
        (self.root / ".github" / "dependabot.yml").write_text(DEPENDABOT, encoding="utf-8")
        (self.root / ".pre-commit-config.yaml").write_text(LOCAL_ONLY, encoding="utf-8")

    def put_lock(self, text: str) -> None:
        """Replace requirements.txt."""
        (self.ansible / "requirements.txt").write_text(text, encoding="utf-8")

    def put_input(self, text: str) -> None:
        """Replace requirements.in."""
        (self.ansible / "requirements.in").write_text(text, encoding="utf-8")

    def put_pip_pin(self, text: str | bytes) -> None:
        """Replace checks/pip-requirements.txt."""
        path = self.ansible / "checks" / "pip-requirements.txt"
        if isinstance(text, bytes):
            path.write_bytes(text)
        else:
            path.write_text(text, encoding="utf-8")

    def findings(self) -> list[str]:
        """Return every finding for the tree as it now stands."""
        return check_pins.run_checks(self.root)[0]

    def assert_found(self, fragment: str) -> None:
        """Assert some finding contains ``fragment``."""
        found = self.findings()
        self.assertTrue(any(fragment in line for line in found), f"{fragment!r} not in {found}")


class ValidTreeTests(PinCase):
    """A tree that follows the rules has no findings, so a finding below is the cause."""

    def test_valid_tree_has_no_findings(self) -> None:
        """The control case: every sabotage below starts from this tree."""
        self.assertEqual(self.findings(), [])

    def test_missing_hook_is_noted_not_failed(self) -> None:
        """With no ansible-lint hook there is nothing to compare, and the run says so."""
        findings, notes = check_pins.run_checks(self.root)
        self.assertEqual(findings, [])
        self.assertTrue(any("no ansible-lint hook" in note for note in notes))
        self.assertTrue(any(f"{len(TOOLS)} locked package(s)" in note for note in notes))

    def test_main_prints_a_clean_summary_and_exits_zero(self) -> None:
        """The command line reports zero findings with status 0."""
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            status = check_pins.main(["--root", str(self.root)])
        self.assertEqual(status, 0)
        self.assertIn("check_pins: 0 finding(s)", out.getvalue())

    def test_main_exits_one_on_a_finding(self) -> None:
        """A single finding makes the command fail and print it."""
        self.put_lock(lock_text() + "extra>=1\n")
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            status = check_pins.main(["--root", str(self.root)])
        self.assertEqual(status, 1)
        self.assertIn("FAIL requirements.txt line", out.getvalue())


class LockTests(PinCase):
    """Every entry of requirements.txt is an exact, hashed pin, and the named tools are there."""

    def test_range_operators_are_refused(self) -> None:
        """A range, a compatible release, a wildcard and a bare name are not exact."""
        for loose in ("ansible-core>=2.21.5", "ansible-core~=2.21", "ansible-core==2.*"):
            with self.subTest(line=loose):
                self.put_lock(lock_text().replace("ansible-core==2.21.5", loose))
                self.assert_found("is not name==version")

    def test_bare_name_is_refused(self) -> None:
        """A bare name floats to whatever the index serves."""
        self.put_lock(lock_text().replace("ansible-core==2.21.5", "ansible-core"))
        self.assert_found("is not name==version")

    def test_entry_without_a_hash_is_refused(self) -> None:
        """An exact pin with no hash installs whatever file the index serves for that version."""
        self.put_lock(lock_text().replace(f" \\\n    {HASH} \\\n    {OTHER_HASH}", "", 1))
        self.assert_found("pins ansible with no --hash")

    def test_hash_of_the_wrong_shape_is_refused(self) -> None:
        """A hash that is not 64 hex digits of sha256 is not a hash."""
        for bad in ("--hash=sha256:abc", "--hash=md5:" + "a" * 32, "--hash=sha256:" + "G" * 64):
            with self.subTest(hash=bad):
                self.put_lock(lock_text().replace(HASH, bad, 1))
                self.assert_found("is not name==version")

    def test_other_requirement_forms_are_refused(self) -> None:
        """An include, an editable install, a URL and an index option are not hashed pins."""
        for odd in (
            "-r other.txt",
            "-e .",
            "git+https://example.invalid/x.git",
            "--index-url https://example.invalid/simple",
            "--find-links https://example.invalid",
        ):
            with self.subTest(line=odd):
                self.put_lock(lock_text() + odd + "\n")
                self.assert_found("is not name==version")

    def test_missing_tool_is_refused(self) -> None:
        """Dropping a named tool, the ansible package included, leaves it unpinned."""
        for name in ("ansible", "ansible-core", "mypy", "molecule-plugins"):
            with self.subTest(tool=name):
                kept = "".join(
                    lock_entry(tool, version)
                    for tool, version in TOOLS.items()
                    if not tool.startswith(name + "[") and tool != name
                )
                self.put_lock(kept)
                self.assert_found(f"does not pin {name}")

    def test_duplicate_pin_is_refused(self) -> None:
        """A tool pinned twice would let the later line win."""
        self.put_lock(lock_text() + lock_entry("ruff", "0.16.0"))
        self.assert_found("pins ruff a second time")

    def test_comments_markers_and_blank_lines_are_allowed(self) -> None:
        """A comment, a blank line and an environment marker carry no loosening."""
        self.put_lock(
            lock_text()
            + "\n# a note between entries\n\n"
            + lock_entry("pywin32", "312", " ; sys_platform == 'win32'", via=VIA_PULLED)
        )
        self.assertEqual(self.findings(), [])

    def test_a_marker_on_a_required_tool_is_refused(self) -> None:
        """A marker narrows where a pin applies, so a required tool would be unpinned elsewhere."""
        for name, version in TOOLS.items():
            with self.subTest(tool=name):
                marked = lock_text().replace(
                    f"{name}=={version} \\", f"{name}=={version} ; sys_platform == 'linux' \\", 1
                )
                self.put_lock(marked)
                bare = check_pins.normalise(name.split("[")[0])
                self.assert_found(f"pins {bare} with an environment marker")

    def test_ruamel_yaml_is_a_required_chosen_tool(self) -> None:
        """ruamel-yaml is imported by the typed_module pattern, so it is chosen and pinned."""
        self.assertIn("ruamel-yaml", check_pins.REQUIRED_TOOLS)
        self.assertNotIn("ruamel-yaml", check_pins.INPUT_TOOLS - {"ruamel-yaml"})

    def test_ruamel_yaml_line_removed_from_the_input_is_refused(self) -> None:
        """Without its line in requirements.in the pin is not chosen on purpose."""
        self.put_input(input_text().replace("ruamel-yaml==0.19.1\n", ""))
        self.assert_found("requirements.in does not name ruamel-yaml")

    def test_ruamel_yaml_removed_from_the_lock_is_refused(self) -> None:
        """Without its pin in the lock nothing installs the module the pattern imports."""
        lock = lock_text().replace(lock_entry("ruamel-yaml", "0.19.1", via=VIA_CHOSEN), "")
        self.put_lock(lock)
        self.assert_found("requirements.txt does not pin ruamel-yaml")

    def test_ruamel_yaml_lock_reason_must_say_it_is_chosen(self) -> None:
        """The lock's reason names requirements.in; a reason that names only ansible-lint is refused."""
        lock = lock_text().replace(
            lock_entry("ruamel-yaml", "0.19.1", via=VIA_CHOSEN),
            lock_entry("ruamel-yaml", "0.19.1", via=VIA_PULLED.replace("ansible", "ansible-lint")),
        )
        self.put_lock(lock)
        self.assert_found("requirements.in names ruamel-yaml but requirements.txt does not mark it")

    def test_ruamel_yaml_reason_as_uv_writes_it_is_accepted(self) -> None:
        """uv writes the chosen line and the pulling tool together, and the check reads that form."""
        lock = lock_text().replace(
            lock_entry("ruamel-yaml", "0.19.1", via=VIA_CHOSEN),
            lock_entry("ruamel-yaml", "0.19.1", via=VIA_CHOSEN_AND_PULLED),
        )
        self.put_lock(lock)
        self.assertEqual(self.findings(), [])

    def test_a_continuation_cannot_hide_an_option_from_the_check(self) -> None:
        """The two shapes install_runtime refuses are refused here too: the line is not a pin."""
        hashed = f"alpha==1.0 {HASH}"
        shapes = {
            "a comment-only line after a continued line": (
                f"{hashed} \\\n # c \\\n--index-url=https://evil.example/simple\n"
            ),
            "a space after the backslash, then a comment": (
                f"{hashed} # c \\ \n--index-url=https://evil.example/simple\n"
            ),
        }
        for name, text in shapes.items():
            with self.subTest(shape=name):
                self.put_lock(lock_text() + text)
                self.assert_found("is not name==version: 'alpha==1.0 ")

    def test_the_lock_reader_is_the_runtime_programs_own(self) -> None:
        """One home: the reader is install_runtime.py's function, not a copy or a wrapper."""
        self.assertIs(check_pins.RUNTIME.logical_lines, check_pins.logical_lines)
        source = Path(check_pins.__file__).read_text(encoding="utf-8")
        self.assertNotIn("def logical_lines", source, "check_pins keeps a copy of the reader")

    def test_the_encoding_check_is_the_runtime_programs_own(self) -> None:
        """One home: the encoding check is install_runtime.py's function."""
        self.assertIs(check_pins.RUNTIME.check_lock_encoding, check_pins.check_lock_encoding)

    def test_the_marker_set_is_the_runtime_programs_own(self) -> None:
        """One home: the marker characters are read from install_runtime.py, not written here."""
        self.assertEqual(check_pins.RUNTIME.MARKER_CHARS, check_pins.MARKER_CHARS)
        source = Path(check_pins.__file__).read_text(encoding="utf-8")
        copy = re.search(r"(?m)^MARKER_CHARS\b[^=\n]*=\s*r?[\"']", source)
        self.assertIsNone(copy, "check_pins keeps a copy of the marker set")

    def test_name_spelling_is_normalised(self) -> None:
        """An underscore or capital in the name still counts as the tool."""
        self.put_lock(lock_text().replace("molecule-plugins", "Molecule_Plugins"))
        self.assertEqual(self.findings(), [])

    def test_normalise_alone_sets_the_name_form(self) -> None:
        """normalise() is the one name rule: dash, dot and underscore runs become a dash."""
        self.assertEqual(check_pins.normalise("Molecule_Plugins"), "molecule-plugins")
        self.assertEqual(check_pins.normalise("ruamel.yaml"), "ruamel-yaml")
        self.assertEqual(check_pins.normalise("a__b..C-d"), "a-b-c-d")

    def test_the_name_regex_is_written_once(self) -> None:
        """One home: locked_packages calls normalise(), so the substitution is written once."""
        source = Path(check_pins.__file__).read_text(encoding="utf-8")
        self.assertEqual(source.count('re.sub(r"[-_.]+", "-"'), 1)

    def test_missing_lock_is_refused(self) -> None:
        """Without the file there is nothing to install from."""
        (self.ansible / "requirements.txt").unlink()
        self.assert_found("requirements.txt cannot be read")

    def test_version_that_only_looks_exact_is_refused(self) -> None:
        """A trailing wildcard or digits from another script are not an exact version."""
        for odd in ("2.21.5.*", "２.21.5"):
            with self.subTest(version=odd):
                self.put_lock(lock_text().replace("2.21.5", odd, 1))
                self.assert_found("is not name==version")


