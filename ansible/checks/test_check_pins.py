    def test_missing_collections_key_is_refused(self) -> None:
        """A file without the key is not the file the harness installs from."""
        self.put("roles: []\n")
        self.assert_found("requirements.yml must hold only 'collections: []'")

    def test_not_yaml_is_refused(self) -> None:
        """A file that does not parse is a finding, not a crash."""
